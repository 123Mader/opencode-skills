#!/data/data/com.termux/files/usr/bin/bash
# sports-safe: 运动安全与损伤预防 (注意事项 / 损伤处理 / 最新文献)
set -euo pipefail
export PYTHONIOENCODING=utf-8

usage() {
    cat <<'EOF'
用法: sports.sh <运动或损伤关键词> [--papers N]

  关键词: 运动项目或损伤类型，如 跑步 / 篮球 / 扭伤 / 中暑 / 跟腱
  选项:   --papers N   显示 N 篇最新研究文献 (默认 5)
示例:
  sports.sh 跑步
  sports.sh 扭伤
  sports.sh 高温天跑步 --papers 8
EOF
}

PAPERS=5
KW=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --papers) PAPERS="$2"; shift ;;
        -h|--help) usage; exit 0 ;;
        *) KW="${KW:-}$1" ;;
    esac
    shift
done
[ -z "$KW" ] && { echo "错误: 缺少关键词" >&2; usage; exit 1; }

