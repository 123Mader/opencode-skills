# ---------- 红旗征 ----------
RED_FLAGS=(
"胸痛|胸闷:运动中胸痛/胸闷/心悸 → 立即停止运动并就医, 警惕心源性问题"
"呼吸困难|气促:异常呼吸困难 → 立即停止"
"心悸|心跳|心律:明显心悸/心律不齐感 → 立即停止并就医"
"头晕|晕厥|昏迷:运动性晕厥 → 立即停止; 意识丧失按急症处理"
"出血:持续出血不止 → 加压止血并就医"
"畸形:关节/肢体畸形 → 疑似骨折脱位, 制动就医"
"无法负重:受伤后无法站立负重 → 就医排除骨折"
"高温|热射|中暑:体温>40℃+意识障碍 = 热射病急症 → 120 + 持续降温"
"抽搐:运动性抽搐 → 立即就医"
)

echo "🏃 运动安全助手 — 关键词: $KW"
echo ""

# 红旗征
hit=0
for f in "${RED_FLAGS[@]}"; do
    pat="${f%%:*}"
    if echo "$KW" | grep -qE "$pat"; then
        [ "$hit" = "0" ] && echo "⚠️  命中红旗征警示:"
        echo "  - ${f#*:}"
        hit=1
    fi
done
[ "$hit" = "1" ] && echo ""

# 运动项目
matched=0
for s in "${SPORTS[@]}"; do
    name="${s%%:*}"
    rest="${s#*:}"
    if echo "$KW" | grep -qE "$name"; then
        [ "$matched" = "0" ] && echo "📋 运动项目注意事项:"
        echo "  ● $name"
        IFS='|' read -ra parts <<<"$rest"
        for p in "${parts[@]}"; do
            echo "    ${p%%:*}${p#*:}"
        done
        echo ""
        matched=1
    fi
done

# 损伤处理
im=0
for s in "${INJURIES[@]}"; do
    name="${s%%:*}"
    rest="${s#*:}"
    if echo "$KW" | grep -qE "$name"; then
        echo "🩹 损伤处理 ($name):"
        echo "    $rest"
        echo ""
        im=1
    fi
done

if [ "$matched" = "0" ] && [ "$hit" = "0" ] && [ "$im" = "0" ]; then
    echo "💡 未匹配到专项表, 以下为通用安全要点: 热身5-10分钟 → 运动30-60分钟 → 整理拉伸; 循序渐进; 不适即停。"
    echo ""
fi

# 最新文献
echo "📚 最新研究文献 (Europe PMC):"
Q=$(python3 -c "import urllib.parse,sys;print(urllib.parse.quote(sys.argv[1]))" "$KW")
curl -sS --max-time 25 "https://www.ebi.ac.uk/europepmc/webservices/rest/search?query=$Q&format=json&pageSize=$PAPERS" 2>/dev/null | python3 -c "
import json,sys
try: d=json.load(sys.stdin)
except Exception: print('  检索失败,请稍后重试'); sys.exit()
print(f'  命中 {d.get(\"hitCount\",0):,} 篇, 最新 {len(d.get(\"resultList\",{}).get(\"result\",[]))} 篇:')
for r in d.get('resultList',{}).get('result',[]):
    print(f'  - [{r.get(\"pubYear\",\"?\")}] {r.get(\"title\",\"\")[:72]}')
    print(f'      PMID:{r.get(\"pmid\",\"-\")}  https://europepmc.org/article/med/{r.get(\"pmid\",\"\")}')
" || echo "  文献检索失败"

